/*
 * fir_coefficients.h
 * FIR Filter Coefficient Tables — CW/SSB Audio Filter
 * TM-AF-001 Rev A
 *
 * Sample rate: Fs = 8000 Hz
 * All coefficients generated using Kaiser window (β = 6 for SSB, β = 8 for CW)
 * Normalized so sum of coefficients = 1.0 (unity DC gain for LP prototype)
 *
 * Bandpass coefficients are formed by spectral inversion of the LP prototype
 * mixed to the desired center frequency.
 *
 * To regenerate with Python/scipy:
 *   from scipy.signal import firwin, kaiser_beta
 *   import numpy as np
 *   Fs = 8000; N = 127
 *   # SSB 300-3000 Hz bandpass:
 *   h = firwin(N, [300/(Fs/2), 3000/(Fs/2)], pass_zero=False, window=('kaiser',6))
 *   # CW 700 Hz ± 250 Hz bandpass:
 *   h = firwin(N, [450/(Fs/2), 950/(Fs/2)], pass_zero=False, window=('kaiser',8))
 *   # Notch 800 Hz ± 50 Hz:
 *   h = firwin(N, [750/(Fs/2), 850/(Fs/2)], pass_zero=True, window=('kaiser',10))
 */

